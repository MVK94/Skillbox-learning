"""Задание 5. Контейнеры

Контейнеры на складе выстроены в ряд по убыванию веса (от более тяжёлых к более лёгким),
причём у некоторых контейнеров может быть одинаковый вес.

На склад привезли ещё один контейнер, который тоже нужно положить на определённое место.

Напишите программу, которая получает на вход невозрастающую последовательность натуральных чисел. Они означают массу
каждого контейнера в ряду. После этого вводится число X — масса нового контейнера. Программа выводит номер, под которым
будет лежать новый контейнер. Если в ряду есть контейнеры с массой, как у нового, то его нужно положить после них.

Обеспечьте контроль ввода: все числа не превышают 200.

Пример:

Количество контейнеров: 8

Введите вес контейнера: 165

Введите вес контейнера: 163

Введите вес контейнера: 160

Введите вес контейнера: 160

Введите вес контейнера: 157

Введите вес контейнера: 157

Введите вес контейнера: 155

Введите вес контейнера: 154

Введите вес нового контейнера: 162

Номер, который получит новый контейнер: 3"""


n = int(input("Количество контейнеров: "))

containers = []

# Ввод контейнеров с проверкой (<= 200)
for _ in range(n):
    weight = int(input("Введите вес контейнера: "))
    while weight > 200:
        print("Ошибка! Вес не должен превышать 200.")
        weight = int(input("Введите вес контейнера: "))
    containers.append(weight)

# Ввод нового контейнера
new_weight = int(input("Введите вес нового контейнера: "))
while new_weight > 200:
    print("Ошибка! Вес не должен превышать 200.")
    new_weight = int(input("Введите вес нового контейнера: "))

# Определяем позицию
position = 1

for weight in containers:
    if weight >= new_weight:
        position += 1
    else:
        break

print("Номер, который получит новый контейнер:", position)
